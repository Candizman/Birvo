const ROLES = {
  SUPER_ADMIN: 'super_admin',
  CLUB_ADMIN: 'club_admin',
  REFEREE: 'referee',
  PLAYER: 'player'
};

const PERMISSIONS = {
  MANAGE_COURSE: [ROLES.SUPER_ADMIN, ROLES.CLUB_ADMIN],
  MANAGE_LEAGUES: [ROLES.SUPER_ADMIN, ROLES.CLUB_ADMIN],
  MANAGE_HANDICAPS: [ROLES.SUPER_ADMIN, ROLES.CLUB_ADMIN, ROLES.REFEREE],
  ENTER_SCORES: [ROLES.SUPER_ADMIN, ROLES.CLUB_ADMIN, ROLES.REFEREE, ROLES.PLAYER],
  ATTEST_SCORES: [ROLES.SUPER_ADMIN, ROLES.CLUB_ADMIN, ROLES.REFEREE, ROLES.PLAYER],
  MANAGE_BILLING: [ROLES.SUPER_ADMIN, ROLES.CLUB_ADMIN],
  RESOLVE_DISPUTES: [ROLES.SUPER_ADMIN, ROLES.CLUB_ADMIN, ROLES.REFEREE]
};

function hasPermission(role, permissionKey) {
  const allowedRoles = PERMISSIONS[permissionKey];
  if (!allowedRoles) return false;
  return allowedRoles.includes(role);
}

module.exports = {
  ROLES,
  PERMISSIONS,
  hasPermission
};
